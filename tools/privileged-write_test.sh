#!/usr/bin/env bash
# Exercise privileged write checks against tracked fixture files.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=/dev/null
. "$HERE/testlib.sh"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/.github/workflows"
GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 git -C "$WORK" init -q
printf "clean\n" > "$WORK/a.sh"
GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 git -C "$WORK" add a.sh
SUT=(bash "$HERE/privileged-write.sh" "$WORK")
printf "%s\n" 'sudo'' cp a b' > "$WORK/a.sh"
expect_refusal copy "a.sh:1:" "${SUT[@]}"
printf '%s\044%s\n' '"' 'privilege" cp a b' > "$WORK/a.sh"
expect_refusal variable "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'sudo'' install -t /etc a b.new' > "$WORK/a.sh"
expect_refusal target_directory "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'sudo'' install --target-directory=/etc a b.new' > "$WORK/a.sh"
expect_refusal target_directory_long "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'sudo'' install -Dt /etc a b.new' > "$WORK/a.sh"
expect_refusal target_directory_cluster "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'sudo'' install -S -d a /etc/file' > "$WORK/a.sh"
expect_refusal suffix_value "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'sudo'' install a /etc/file # x.new' > "$WORK/a.sh"
expect_refusal comment_destination "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'sudo'' install -oroot -m 0644 a b.new' > "$WORK/a.sh"
expect_pass owner_attached "${SUT[@]}"
printf '%s\n' 'sudo'' install -Dm 0644 a /etc/x.new' > "$WORK/a.sh"
expect_pass cluster_mode_staged "${SUT[@]}"
printf "%s\n" 'sudo'' install a /etc/x' > "$WORK/a.sh"
expect_refusal install_final "a.sh:1:" "${SUT[@]}"
printf '%s\134\n' 'sudo'' install -m 0644 a ' > "$WORK/a.sh"
expect_refusal install_continuation "a.sh:1:" "${SUT[@]}"
printf '%s\n' '$''privilege cp a b' > "$WORK/a.sh"
expect_refusal variable_unquoted "a.sh:1:" "${SUT[@]}"
printf '%s\n' '$''{privilege} cp a b' > "$WORK/a.sh"
expect_refusal variable_braced "a.sh:1:" "${SUT[@]}"
printf '%s\n' '"$''{privilege}" cp a b' > "$WORK/a.sh"
expect_refusal variable_quoted_braced "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'do''as cp a b' > "$WORK/a.sh"
expect_refusal doas_copy "a.sh:1:" "${SUT[@]}"
printf '"\044%s" install -m 0644 "\044%s" "\044%s"\n' privilege source target > "$WORK/a.sh"
expect_refusal variable_install_final "a.sh:1:" "${SUT[@]}"
printf "%s\n" 'sudo'' cat a > /etc/x' > "$WORK/a.sh"
expect_refusal redirect "a.sh:1:" "${SUT[@]}"
printf "%s\n" 'sudo'' tee /etc/x' > "$WORK/a.sh"
expect_refusal tee "a.sh:1:" "${SUT[@]}"
printf "clean\n" > "$WORK/a.sh"
printf "%s\n" 'run: sudo'' cp a b' > "$WORK/.github/workflows/w.yml"
GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 git -C "$WORK" add .github/workflows/w.yml
expect_refusal workflow ".github/workflows/w.yml:1:" "${SUT[@]}"
printf "clean\n" > "$WORK/.github/workflows/w.yml"
printf "\t%s\n" 'sudo'' cp a b' > "$WORK/Makefile"
GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 git -C "$WORK" add Makefile
expect_refusal makefile "Makefile:1:" "${SUT[@]}"
printf "\t%s\n" '$''(SUDO) cp a b' > "$WORK/Makefile"
expect_refusal make_variable "Makefile:1:" "${SUT[@]}"
printf "clean\n" > "$WORK/Makefile"
printf '"\044%s" install -m 0644 "\044%s" "\044%s"\n' privilege source target.new > "$WORK/a.sh"
expect_pass variable_staged "${SUT[@]}"
printf '%s\n' 'sudo'' install -d -m 0755 /etc/x' > "$WORK/a.sh"
expect_pass install_directory "${SUT[@]}"
printf '%s\134\n%s\n' 'sudo'' install -d -m 0755 ' '  /etc/x' > "$WORK/a.sh"
expect_pass install_directory_continuation "${SUT[@]}"
printf '%s\n' 'install a /etc/x' > "$WORK/a.sh"
expect_pass unprivileged_install "${SUT[@]}"
printf "%s\n" 'sudo'' install -m 0644 a b.new' 'sudo'' mv -f b.new b' > "$WORK/a.sh"
expect_pass staged "${SUT[@]}"
printf "%s\n" '# sudo'' cp a b' > "$WORK/a.sh"
expect_pass comment "${SUT[@]}"
printf "%s\n" 'sudo'' cp a b' > "$WORK/b.sh"
expect_pass untracked "${SUT[@]}"
printf "%s\n" 'sudo'' cp a b' > "$WORK/README.md"
GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 git -C "$WORK" add README.md
expect_pass ignored_type "${SUT[@]}"
printf '%s\n' 'sudo'' chown "$''SUDO_USER" /x' > "$WORK/a.sh"
expect_pass sudo_user_argument "${SUT[@]}"
printf 'chown "\044{%s}" /x\n' 'SUDO_''UID' > "$WORK/a.sh"
expect_pass sudo_uid_argument "${SUT[@]}"
printf '%s\n' 'echo "$''SUDO_COMMAND" ran' > "$WORK/a.sh"
expect_pass sudo_command_argument "${SUT[@]}"
printf '%s\n' '"$''sudo_cmd" cp a b' > "$WORK/a.sh"
expect_refusal sudo_named_variable "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'echo "$''SUDO_USER" && sudo'' cp a b' > "$WORK/a.sh"
expect_refusal sudo_user_then_copy "a.sh:1:" "${SUT[@]}"
printf '%s\n' 'echo "$''SUDO_USER" sudo'' cp a b' > "$WORK/a.sh"
expect_refusal sudo_user_before_launcher "a.sh:1:" "${SUT[@]}"
expect_pass repository bash "$HERE/privileged-write.sh"
echo "privileged-write: all planted cases pass"
